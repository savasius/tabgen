export type Lang = 'tr' | 'en'
export type TKey = keyof Dict
const dicts: Record<Lang, Dict> = { tr, en }

type T = (k: TKey, vars?: Record<string, string | number>) => string
const Ctx = createContext<{ t: T; lang: Lang; setLang: (l: Lang) => void }>(null!)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('lang') as Lang) || 'tr')
  const setLang = (l: Lang) => { localStorage.setItem('lang', l); setLangState(l) }
  const t: T = (k, vars) => {
    let s: string = dicts[lang][k] ?? k
    for (const [name, v] of Object.entries(vars ?? {})) s = s.replace(`{${name}}`, String(v))
    return s
  }
  return <Ctx.Provider value={{ t, lang, setLang }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
